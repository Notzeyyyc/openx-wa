#!/usr/bin/env node
/**
 * OpenXX MCP Auth Setup Script (Node.js version)
 * Generates a random token and sets it for both MCP server and WhatsApp bot.
 */

import fs from 'fs';
import crypto from 'crypto';
import path from 'path';

const ENV_FILE = '.env';
const ENV_EXAMPLE = '.env.example';

console.log('=== OpenXX MCP Auth Setup ===\n');

// Generate random token
const token = crypto.randomBytes(32).toString('hex');
console.log(`Generated token: ${token.slice(0, 8)}...${token.slice(-8)}\n`);

// Create .env if not exists
const envPath = path.resolve(process.cwd(), ENV_FILE);
const envExamplePath = path.resolve(process.cwd(), ENV_EXAMPLE);

if (!fs.existsSync(envPath)) {
    if (fs.existsSync(envExamplePath)) {
        fs.copyFileSync(envExamplePath, envPath);
        console.log('Created .env from .env.example');
    } else {
        fs.writeFileSync(envPath, '');
        console.log('Created empty .env');
    }
}

// Read current .env
let envContent = fs.readFileSync(envPath, 'utf-8');

// Update or add OPENX_MCP_API_KEY
const keyRegex = /^OPENX_MCP_API_KEY=.*$/m;
if (keyRegex.test(envContent)) {
    envContent = envContent.replace(keyRegex, `OPENX_MCP_API_KEY=${token}`);
    console.log('Updated OPENX_MCP_API_KEY in .env');
} else {
    envContent = envContent.trimEnd() + '\n\n# MCP Auth Token (generated by setup-mcp-auth.mjs)\n' + `OPENX_MCP_API_KEY=${token}\n`;
    console.log('Added OPENX_MCP_API_KEY to .env');
}

fs.writeFileSync(envPath, envContent);

console.log('\n=== Setup Complete ===\n');
console.log('Token saved to .env as OPENX_MCP_API_KEY\n');
console.log('For MCP Server (Termux/Railway), set this env var:');
console.log(`  export OPENX_HTTP_API_KEY=${token}\n`);
console.log("Or add to your MCP server's .env:");
console.log(`  OPENX_HTTP_API_KEY=${token}\n`);
console.log('IMPORTANT: Both values must match for auth to work.');
